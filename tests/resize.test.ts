import { planResize, type ResizeSettings } from "../src/lib/image-resize";
let fails = 0;
const base: ResizeSettings = { mode: "pixels", width: 1200, height: null, lock: true, driver: "width", percent: 50, preset: "ig-square", fit: "cover", format: "original", quality: 0.85 };
const t = (name: string, cond: boolean, info: unknown) => { if (!cond) fails++; console.log(`${cond ? "PASS" : "FAIL"} ${name}`, cond ? "" : info); };
const p = (srcW: number, srcH: number, s: Partial<ResizeSettings>) => planResize(srcW, srcH, { ...base, ...s });

let r = p(4000, 3000, {});
t("locked width keeps 4:3", r.ok && r.plan.w === 1200 && r.plan.h === 900, r);
r = p(3000, 4000, { driver: "height", height: 800, width: 1200 });
t("locked height driver", r.ok && r.plan.h === 800 && r.plan.w === 600, r);
r = p(1000, 500, { mode: "percent", percent: 25 });
t("percent 25%", r.ok && r.plan.w === 250 && r.plan.h === 125, r);
r = p(4000, 3000, { mode: "preset", preset: "ig-square", fit: "cover" });
t("preset cover crops centre", r.ok && r.plan.w === 1080 && r.plan.h === 1080 && r.plan.cropped && r.plan.sx === 500 && r.plan.sw === 3000, r);
r = p(4000, 3000, { mode: "preset", preset: "ig-story", fit: "contain" });
t("preset contain pads, no distortion", r.ok && r.plan.padded && Math.abs(r.plan.dw / r.plan.dh - 4 / 3) < 1e-9 && r.plan.dw === 1080, r);
r = p(800, 600, { width: 1600 });
t("upscale flagged", r.ok && r.plan.upscaled, r);
r = p(800, 600, { width: 400 });
t("downscale not flagged", r.ok && !r.plan.upscaled, r);
r = p(800, 600, { width: 0 });
t("zero width rejected", !r.ok, r);
r = p(800, 600, { width: 20000 });
t("over max side rejected", !r.ok, r);
r = p(800, 600, { lock: false, width: 300, height: null });
t("unlocked needs both", !r.ok, r);
r = p(800, 600, { lock: false, width: 400, height: 300 });
t("unlocked same shape no crop", r.ok && !r.plan.cropped && !r.plan.padded, r);
r = p(1, 1, { mode: "percent", percent: 1 });
t("never below 1px", r.ok && r.plan.w === 1 && r.plan.h === 1, r);
if (fails) process.exitCode = 1;
